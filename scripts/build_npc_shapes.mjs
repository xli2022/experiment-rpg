// Derive a compact head-shape field from the bundled CC0 MakeHuman targets.
// Uses the same bind-space conversion as build_characters.py; no Blender needed.
import { readFileSync, writeFileSync } from 'node:fs';
const source = new URL('../assets/characters/source/', import.meta.url);
const read = name => readFileSync(new URL(name, source), 'utf8').split(/\r?\n/);
const vertices = [], body = new Set(); let group;
for (const line of read('base.obj')) {
  const a = line.trim().split(/\s+/);
  if (a[0] === 'v') vertices.push(a.slice(1, 4).map(Number));
  if (a[0] === 'g') group = a[1];
  if (a[0] === 'f' && group === 'body') a.slice(1).forEach(v => body.add(Number(v.split('/')[0]) - 1));
}
function shaped(names) {
  const v = vertices.map(p => [...p]);
  for (const name of names) for (const line of read(name)) {
    if (!line || line.startsWith('#')) continue;
    const [i, ...d] = line.trim().split(/\s+/).map(Number); d.forEach((value, axis) => v[i][axis] += value);
  }
  return v;
}
const male = shaped(['male.target', 'male-face.target']), female = shaped(['female.target', 'female-face.target']);
const floor = Math.min(...[...body].map(i => male[i][1])), ceiling = Math.max(...[...body].map(i => male[i][1]));
const scale = 1.91 / (ceiling - floor);
const femaleTop = Math.max(...[...body].map(i => female[i][1]));
const field = [];
for (const i of body) {
  const m = male[i], f = female[i], y = (m[1] - floor) * scale;
  if (y < 1.54 || Math.abs(m[0] * scale) > .15) continue;
  // Align crown height with the existing animated head. Overall stature and
  // body build are separate authored profile values, not skeleton changes.
  field.push(...[-m[0] * scale, y, -m[2] * scale, -(f[0] - m[0]) * scale, (f[1] - m[1] + ceiling - femaleTop) * scale, -(f[2] - m[2]) * scale].map(v => Number(v.toFixed(6))));
}
const rows = [];
for (let i = 0; i < field.length; i += 6) rows.push(`  ${field.slice(i, i + 6).join(', ')},`);
writeFileSync(new URL('../src/npc-head-shape.js', import.meta.url), `// Generated by scripts/build_npc_shapes.mjs from CC0 MakeHuman data.\n// Rows: bind-space x, y, z, then the female-shape displacement x, y, z.\nexport default [\n${rows.join('\n')}\n];\n`);
console.log(`Generated ${field.length / 6} head-shape samples.`);
